// Deterministic seed data so every restart shows the same desk.
// Times are stored as "hours ago" and turned into dates at startup.

export interface SeedTicket {
  title: string;
  customer: string;
  priority: "low" | "medium" | "high" | "urgent";
  status: "open" | "pending" | "resolved" | "closed";
  assignee: string;
  hoursAgo: number;
}

export const AGENTS = [
  { id: "a1", name: "Maya", team: "Billing" },
  { id: "a2", name: "Omer", team: "Platform" },
  { id: "a3", name: "Lena", team: "Platform" },
  { id: "a4", name: "Ravi", team: "Onboarding" },
];

const CUSTOMERS = ["Acme", "Globex", "Initech", "Umbrella", "Hooli", "Stark", "Wayne", "Soylent"];
const TOPICS = [
  "Invoice shows wrong VAT",
  "SSO login loops",
  "Webhook retries failing",
  "Export to CSV times out",
  "Cannot invite teammates",
  "API rate limit too low",
  "Dashboard loads slowly",
  "Refund not received",
  "2FA codes rejected",
  "Data import stuck at 90%",
];
const PRIORITIES = ["low", "medium", "high", "urgent"] as const;
const STATUSES = ["open", "open", "pending", "resolved", "closed"] as const;

/**
 * 36 tickets generated by a fixed formula. Active tickets are 0-30h old (so
 * only some breach their SLA); finished ones are spread over ~30 days.
 */
export const SEED_TICKETS: SeedTicket[] = Array.from({ length: 36 }, (_, i) => {
  const status = STATUSES[(i * 3) % STATUSES.length];
  const active = status === "open" || status === "pending";
  return {
    title: TOPICS[i % TOPICS.length],
    customer: CUSTOMERS[(i * 3) % CUSTOMERS.length],
    priority: PRIORITIES[(i * 7) % PRIORITIES.length],
    status,
    assignee: i % 6 === 0 ? "unassigned" : AGENTS[i % AGENTS.length].name,
    hoursAgo: active ? Math.round(((i * 7.3) % 30) * 10) / 10 + 0.5 : Math.round((i * 19.7) % (24 * 30)) + 1,
  };
});
